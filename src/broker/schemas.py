class BarData(BaseModel):
    """Single OHLCV bar returned by AlpacaClient.get_bars()."""

    symbol: str
    timestamp: datetime     # UTC, start of bar
    open: float
    high: float
    low: float
    close: float
    volume: float
    vwap: float | None = None


class ClockSnapshot(BaseModel):
    """Alpaca server clock snapshot used for drift detection.

    ``drift_seconds = local_timestamp - alpaca_timestamp``
    Positive value means the local clock is ahead of Alpaca's.
    Negative value means the local clock is behind.
    """

    alpaca_timestamp: datetime
    local_timestamp: datetime
    drift_seconds: float    # local - alpaca (positive = local ahead)
    is_open: bool
    next_open: datetime | None = None
    next_close: datetime | None = None


class OrderStatusResult(BaseModel):
    """Current state of an order fetched after submission.

    Returned by AlpacaClient.get_order() and consumed by the engine and
    stream callbacks to reconcile fills.  Distinct from OrderSubmitResult,
    which is the snapshot captured at submission time only.
    """

    alpaca_order_id: str
    client_order_id: str
    status: str             # "new" | "filled" | "partially_filled" | "canceled" | "rejected" | …
    submitted_at: datetime
    filled_at: datetime | None = None
    canceled_at: datetime | None = None
    filled_qty: float = 0.0
    filled_avg_price: float | None = None
    side: OrderSide
    symbol: str
    qty: float


class MarketCalendarDay(BaseModel):
    """Single trading-day entry from the Alpaca market calendar.

    Times are stored in UTC for unambiguous scheduling.
    Use ``open_et`` / ``close_et`` properties for ET wall-clock display.
    The mapper in AlpacaClient localizes the naive ET datetimes returned by
    the SDK before constructing this model.
    """

    date: date
    session_open_utc: datetime
    session_close_utc: datetime

    @field_validator("session_open_utc", "session_close_utc")
    @classmethod
    def _must_be_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            raise ValueError("session times must be timezone-aware UTC")
        if v.utcoffset() != timedelta(0):
            raise ValueError(f"session times must be in UTC, got offset {v.utcoffset()}")
        return v

    @property
    def open_et(self) -> time:
        return self.session_open_utc.astimezone(ZoneInfo("America/New_York")).time()

    @property
    def close_et(self) -> time:
        return self.session_close_utc.astimezone(ZoneInfo("America/New_York")).time()


