class TradeUpdateEvent(BaseModel):
    """Trade lifecycle event received from Alpaca's TradingStream."""

    event: str
    order: OrderStatusResult
    timestamp: datetime  # UTC, tz-aware

    @field_validator("timestamp")
    @classmethod
    def _must_be_tz_aware(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            raise ValueError("timestamp must be timezone-aware")
        return v


